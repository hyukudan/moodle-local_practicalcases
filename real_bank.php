        'publicado-cautela-territorial',
    ];

    $visible = [];
    $seen = [];
    foreach ($priority as $tag) {
        if (in_array($tag, $tags, true) && !isset($seen[$tag])) {
            $seen[$tag] = true;
            $visible[] = local_cp_real_bank_human_tag($tag);
        }
        if (count($visible) >= 4) {
            break;
        }
    }
    return $visible;
}

/**
 * Pick one compact badge for a case card.
 *
 * @param string|null $tagsjson JSON tags
 * @return string
 */
function local_cp_real_bank_card_badge(?string $tagsjson): string {
    $tags = json_decode((string)$tagsjson, true);
    if (!is_array($tags)) {
        return '';
    }
    if (in_array('imagenes-enunciado', $tags, true) || in_array('visual-comprobado', $tags, true)) {
        return 'Con imágenes';
    }
    if (in_array('supuesto-reutilizado', $tags, true) || in_array('mismo-supuesto-oficial-2022-2023', $tags, true)) {
        return 'Reutilizado';
    }
    if (in_array('seleccion-parcial', $tags, true)) {
        return 'Parcial';
    }
    if (in_array('castellano-revisado', $tags, true) && in_array('feedback-pedagogico', $tags, true)) {
        return 'Revisado';
    }
    if (in_array('clave-oficial', $tags, true) || in_array('plantilla-oficial', $tags, true)) {
        return 'Clave oficial';
    }
    if (in_array('caso-historico-oficial', $tags, true)) {
        return 'Caso histórico';
    }
    return '';
}

/**
 * Render segmented filter links.
 *
 * @param string $title Filter title
 * @param string $param Param name
 * @param string $current Current value
 * @param array $options Option definitions
 * @return string HTML
 */
function local_cp_real_bank_filter_group(string $title, string $param, string $current, array $options, array $counts = []): string {
    $html = html_writer::tag('div', s($title), ['class' => 'cp-real-filter-title']);
    $links = '';
    foreach ($options as $key => $def) {
        $url = local_cp_real_bank_url([$param => $key, 'page' => null]);
        $class = 'cp-real-chip' . ($current === $key ? ' is-active' : '');
        $count = $counts[$key] ?? null;
        if ($key !== '' && $count === 0 && $current !== $key) {
            continue;
        }
        $label = s($def['label']);
        if ($count !== null) {
            $label .= html_writer::span((string)$count, 'cp-real-chip-count');
        }
        $attrs = ['class' => $class];
        if ($current === $key) {
            $attrs['aria-current'] = 'true';
        }
        $links .= html_writer::link($url, $label, $attrs);
    }
    return html_writer::div($html . html_writer::div($links, 'cp-real-chiprow'), 'cp-real-filter');
}

