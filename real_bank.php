/**
 * Add LIKE conditions requiring at least one tag from a filter group.
 *
 * @param array $where SQL where clauses
 * @param array $params SQL params
 * @param string[] $tags Tags
 * @param string $prefix Param prefix
 */
function local_cp_real_bank_add_any_tag(array &$where, array &$params, array $tags, string $prefix): void {
    global $DB;

    if (!$tags) {
        return;
    }

    $parts = [];
    foreach (array_values($tags) as $i => $tag) {
        $key = $prefix . $i;
        $parts[] = $DB->sql_like('c.tags', ':' . $key, false);
        $params[$key] = local_cp_real_bank_tag_param($tag);
    }
    $where[] = '(' . implode(' OR ', $parts) . ')';
}

/**
 * Add LIKE conditions for a filter definition.
 *
 * @param array $where SQL where clauses
 * @param array $params SQL params
 * @param array $filter Filter definition
 * @param string $prefix Param prefix
 */
function local_cp_real_bank_add_filter(array &$where, array &$params, array $filter, string $prefix): void {
    global $DB;

    $tags = $filter['tags'] ?? [];
    if (!$tags) {
        return;
    }

    if (($filter['mode'] ?? 'any') !== 'all') {
        local_cp_real_bank_add_any_tag($where, $params, $tags, $prefix);
        return;
    }

    foreach (array_values($tags) as $i => $tag) {
        $key = $prefix . $i;
        $where[] = $DB->sql_like('c.tags', ':' . $key, false);
        $params[$key] = local_cp_real_bank_tag_param($tag);
    }
}

