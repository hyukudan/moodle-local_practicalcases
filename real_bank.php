/**
 * Build a URL for a filter change.
 *
 * @param array $overrides Param overrides
 * @return moodle_url
 */
function local_cp_real_bank_url(array $overrides = []): moodle_url {
    global $sort;

    $params = array_merge([
        'territory' => optional_param('territory', '', PARAM_ALPHANUMEXT),
        'area' => optional_param('area', '', PARAM_ALPHANUMEXT),
        'source' => optional_param('source', '', PARAM_ALPHANUMEXT),
        'q' => optional_param('q', '', PARAM_TEXT),
        'sort' => $sort,
    ], $overrides);

    foreach ($params as $key => $value) {
        if ($value === '' || $value === null || ($key === 'sort' && $value === 'recent')) {
            unset($params[$key]);
        }
    }
    return new moodle_url('/local/casospracticos/real_bank.php', $params);
}

