    global $DB;

    $search = trim($search);
    if ($search === '') {
        return;
    }

    $where[] = '(' . $DB->sql_like('c.name', ':' . $prefix . 'name', false) . ' OR '
        . $DB->sql_like('c.statement', ':' . $prefix . 'statement', false) . ' OR '
        . $DB->sql_like('c.tags', ':' . $prefix . 'tags', false) . ')';
    $escaped = '%' . $DB->sql_like_escape($search) . '%';
    $params[$prefix . 'name'] = $escaped;
    $params[$prefix . 'statement'] = $escaped;
    $params[$prefix . 'tags'] = $escaped;
}

